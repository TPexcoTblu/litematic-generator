package com.tpexcotblu.litematicgen.schematic;

import java.io.BufferedOutputStream;
import java.io.DataOutputStream;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.zip.GZIPOutputStream;

/** Writes the subset of Litematic v7 used by generated shapes; no Minecraft or loader API needed. */
public final class LitematicWriter {
    private LitematicWriter() {}

    public static void write(Path target, SchematicVolume volume, String name, String author,
                             int minecraftDataVersion) throws IOException {
        Path absolute = target.toAbsolutePath();
        Files.createDirectories(absolute.getParent());
        Path temporary = Files.createTempFile(absolute.getParent(), ".litematic-", ".tmp");
        try {
            try (var out = new DataOutputStream(new BufferedOutputStream(
                    new GZIPOutputStream(Files.newOutputStream(temporary))))) {
                tag(out, 10, "");
                integer(out, "Version", 7);
                integer(out, "SubVersion", 1);
                integer(out, "MinecraftDataVersion", minecraftDataVersion);
                tag(out, 10, "Metadata");
                string(out, "Name", name);
                string(out, "Author", author);
                string(out, "Description", "Generated by Litematic Generator");
                long now = System.currentTimeMillis();
                longTag(out, "TimeCreated", now);
                longTag(out, "TimeModified", now);
                integer(out, "RegionCount", 1);
                integer(out, "TotalVolume", volume.volume());
                integer(out, "TotalBlocks", volume.blockCount());
                vector(out, "EnclosingSize", volume.width(), volume.height(), volume.depth());
                out.writeByte(0);
                tag(out, 10, "Regions");
                tag(out, 10, "Generated");
                vector(out, "Position", 0, 0, 0);
                vector(out, "Size", volume.width(), volume.height(), volume.depth());
                tag(out, 9, "BlockStatePalette");
                out.writeByte(10);
                out.writeInt(2);
                string(out, "Name", "minecraft:air");
                out.writeByte(0);
                string(out, "Name", "minecraft:smooth_stone");
                out.writeByte(0);
                tag(out, 12, "BlockStates");
                out.writeInt(volume.states().length);
                for (long word : volume.states()) out.writeLong(word);
                for (String list : new String[]{"Entities", "TileEntities", "PendingBlockTicks", "PendingFluidTicks"}) {
                    tag(out, 9, list);
                    out.writeByte(10);
                    out.writeInt(0);
                }
                out.writeByte(0);
                out.writeByte(0);
                out.writeByte(0);
            }
            try {
                Files.move(temporary, absolute, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING);
            } catch (java.nio.file.AtomicMoveNotSupportedException e) {
                Files.move(temporary, absolute, StandardCopyOption.REPLACE_EXISTING);
            }
        } finally {
            Files.deleteIfExists(temporary);
        }
    }

    private static void tag(DataOutputStream out, int type, String name) throws IOException {
        out.writeByte(type);
        out.writeUTF(name);
    }
    private static void integer(DataOutputStream out, String name, int value) throws IOException {
        tag(out, 3, name); out.writeInt(value);
    }
    private static void longTag(DataOutputStream out, String name, long value) throws IOException {
        tag(out, 4, name); out.writeLong(value);
    }
    private static void string(DataOutputStream out, String name, String value) throws IOException {
        tag(out, 8, name); out.writeUTF(value);
    }
    private static void vector(DataOutputStream out, String name, int x, int y, int z) throws IOException {
        tag(out, 10, name);
        integer(out, "x", x); integer(out, "y", y); integer(out, "z", z);
        out.writeByte(0);
    }
}
